/* هم‌ارزی‌های قطعی که با تطبیق خودکار به‌دست نمی‌آیند (نام متفاوت، یک سند) */
const LAW_ALIASES = {
  'قانون حمایت حقوق مؤلفان و مصنفان و هنرمندان': 'authors-rights-law',
  'قانون اصلاح قسمتی از قانون تجارت (مواد ۲۱ الی ۹۳)': 'commercial-amendment-1347',
};

/* ------------------------------------------------------------------ *
 * نرمال‌سازی و تطبیق
 * ------------------------------------------------------------------ */
const STOPWORDS = new Set(['از', 'و', 'در', 'به', 'با', 'بر', 'برای', 'ال', 'الی', 'تا']);

function normalize(text) {
  return String(text)
    .replace(/[\u064B-\u0652\u0670\u0640\u0654\u0655\u06D6-\u06ED]/g, '')
    .replace(/\u064A/g, 'ی')
    .replace(/\u0643/g, 'ک')
    .replace(/\u0629/g, 'ه')
    .replace(/[\u200b-\u200f\u202a-\u202e\uFEFF]/g, '')
    .replace(/[()（）\[\]\/\\.,،؛;:؟?!«»"']/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function words(text) {
  return new Set(normalize(text).split(' ').filter((w) => w && !STOPWORDS.has(w)));
}

function subsetOf(a, b) {
  for (const w of a) if (!b.has(w)) return false;
  return true;
}

/** تطبیق یک عنوان با فهرست اشیاء موجود */
function findMatch(title, records, getTitle) {
  const n = normalize(title);
  const w = words(title);

  for (const rec of records) {
    if (normalize(getTitle(rec)) === n) return { rec, rule: 'عنوان دقیق' };
  }
  const aliasId = LAW_ALIASES[title];
  if (aliasId) {
    const rec = records.find((r) => r.id === aliasId);
    if (rec) return { rec, rule: 'هم‌ارز اعلام‌شده' };
  }
  for (const rec of records) {
    const rn = normalize(getTitle(rec));
    if (rn.includes(n) || n.includes(rn)) return { rec, rule: 'تطبیق زیررشته‌ای' };
  }
  for (const rec of records) {
    const rw = words(getTitle(rec));
    if (subsetOf(w, rw) || subsetOf(rw, w)) return { rec, rule: 'تطبیق واژگانی' };
  }
  return null;
}

