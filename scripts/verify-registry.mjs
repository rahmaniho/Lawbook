const pointer = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/data/version.json'), 'utf8'));
const catalog = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'public/data/v', pointer.version, 'catalog.json'), 'utf8'),
);

const laws = catalog.laws;
const entities = (catalog.entityGroups || []).flatMap((g) => ({ ...g, items: g.items }));
const allEntities = (catalog.entityGroups || []).flatMap((g) => g.items.map((i) => ({ ...i, groupTitle: g.title })));

const preexistingIds = new Set(
  JSON.parse(fs.readFileSync(path.join(ROOT, 'data/curated/catalog.json'), 'utf8')).laws.map((l) => l.id),
);

let okLaws = 0;
let addedLaws = 0;
const missingLaws = [];
const lawRows = [];

for (const title of EXPECTED_LAWS) {
  const hit = findMatch(title, laws, (l) => l.title);
  if (!hit) {
    missingLaws.push(title);
    continue;
  }
  const isNew = !preexistingIds.has(hit.rec.id);
  if (isNew) addedLaws++;
  else okLaws++;
  lawRows.push({ title, id: hit.rec.id, rule: hit.rule, state: isNew ? '➕ افزوده‌شده' : '✅ از پیش موجود' });
}

let okEntities = 0;
const missingEntities = [];
const duplicateInInput = [];
const seenEntityTitles = new Map();
const entityRows = [];

for (const [groupTitle, items] of Object.entries(EXPECTED_ENTITIES)) {
  for (const title of items) {
    if (seenEntityTitles.has(title)) {
      duplicateInInput.push({ title, first: seenEntityTitles.get(title), second: groupTitle });
      continue;
    }
    seenEntityTitles.set(title, groupTitle);

    const hit = findMatch(title, allEntities, (e) => e.title);
    if (!hit) {
      missingEntities.push(`${groupTitle} → ${title}`);
      continue;
    }
    okEntities++;
    entityRows.push({ title, group: hit.rec.groupTitle, rule: hit.rule });
  }
}

